#!/usr/bin/env bash
# fm-cloudify-arm-check.sh - arm the watcher poll for a cloudified task.
#
# Usage: fm-cloudify-arm-check.sh <task-id> <cursor-agent-id>
#
# Writes state/<id>.check.sh and binds its bytes with bin/fm-check-register.sh,
# which is the existing seam for a custom check. There is deliberately NO second
# watcher, daemon or timer: a cloud run transition arrives as an ordinary
# `check:` wake on the same cadence as PR merge polling.
#
# The generated check obeys the custom-check contract: an ordinary single-link
# mode-0700 file, it prints ONE line only when firstmate should wake and nothing
# otherwise, and it finishes well inside FM_CHECK_TIMEOUT because it makes at
# most two API calls.
#
# It fires once, not every sweep. The watcher polls every FM_CHECK_INTERVAL, so a
# check that printed on every poll after the run finished would wake firstmate
# repeatedly for one event. A marker file records that the terminal transition
# was already reported; bin/fm-bare-metal.sh removes it along with the check.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

[ "$#" -eq 2 ] || { echo 'usage: fm-cloudify-arm-check.sh <task-id> <cursor-agent-id>' >&2; exit 2; }
ID=$1
AGENT=$2
case $ID in '' | *[!A-Za-z0-9_-]*) echo "fm-cloudify-arm-check: invalid task id: $ID" >&2; exit 2 ;; esac
case $AGENT in '' | *[!A-Za-z0-9_-]*) echo "fm-cloudify-arm-check: invalid agent id: $AGENT" >&2; exit 2 ;; esac
[ -d "$STATE" ] || { echo "fm-cloudify-arm-check: no state directory at $STATE" >&2; exit 1; }

CHECK="$STATE/$ID.check.sh"
if [ -e "$CHECK" ]; then
  echo "fm-cloudify-arm-check: $CHECK already exists; refusing to overwrite an armed check" >&2
  exit 1
fi

umask 077
TMP=$(mktemp "$STATE/.fm-cloudify-check.XXXXXX") || exit 1
trap '[ -z "${TMP:-}" ] || rm -f -- "$TMP"' EXIT HUP INT TERM

# The single quotes below are deliberate: this block WRITES a script, so every
# `$` must survive into the generated file rather than expanding here. Only the
# four printf'd values above are interpolated, and each is validated first.
# shellcheck disable=SC2016
{
  printf '%s\n' '#!/usr/bin/env bash'
  printf '%s\n' '# Generated by bin/fm-cloudify-arm-check.sh - cloudified task run poll.'
  printf '%s\n' '# Prints one line when the cloud run reaches a terminal state, then stays'
  printf '%s\n' '# silent. Removed by bin/fm-bare-metal.sh when the task comes back.'
  printf '%s\n' 'set -eu'
  printf 'FM_HOME=%s\n' "$FM_HOME"
  printf 'ROOT=%s\n' "$FM_ROOT"
  printf 'ID=%s\n' "$ID"
  printf 'AGENT=%s\n' "$AGENT"
  printf '%s\n' 'MARK="$FM_HOME/state/$ID.cursor-reported"'
  printf '%s\n' '[ ! -e "$MARK" ] || exit 0'
  printf '%s\n' 'out=$(FM_HOME="$FM_HOME" "$ROOT/bin/fm-cursor.sh" runs "$AGENT" --limit 1 --json 2>/dev/null) || exit 0'
  printf '%s\n' 'status=$(printf "%s" "$out" | jq -r ".runs[0].status // empty" 2>/dev/null) || exit 0'
  printf '%s\n' 'case "$status" in'
  printf '%s\n' '  FINISHED|ERROR|CANCELLED|EXPIRED) ;;'
  printf '%s\n' '  *) exit 0 ;;'
  printf '%s\n' 'esac'
  printf '%s\n' ': > "$MARK" 2>/dev/null || true'
  printf '%s\n' 'printf "cloud run %s for %s\\n" "$status" "$ID"'
} > "$TMP"

chmod 0700 "$TMP" || exit 1
mv -f -- "$TMP" "$CHECK" || exit 1
TMP=

"$SCRIPT_DIR/fm-check-register.sh" "$ID"
